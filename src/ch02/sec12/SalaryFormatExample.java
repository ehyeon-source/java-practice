package ch02.sec12;

/*
 * [문제 상황: 사원 실적 명세서 테이블 출력]
 * 
 * 1. 데이터 준비: 사원 번호(empNo)는 75, 사원 이름(empName)은 "이순신", 이번 달 실적 점수(score)는 85.6789이다. 각각 알맞은 타입의 변수에 할당한다.
 * 2. 포맷팅 1 (0 채우기): 사원 번호는 총 5자리로 출력하되, 빈자리는 0으로 채워서 출력되도록 포맷을 지정한다.
 * 3. 포맷팅 2 (왼쪽 정렬): 사원 이름은 총 8자리의 공간을 확보하고, 왼쪽으로 정렬하여 출력되도록 포맷을 지정한다.
 * 4. 포맷팅 3 (소수점 제어): 실적 점수는 총 7자리의 공간을 차지하며, 소수점 아래 둘째 자리까지만 나타나도록 포맷을 지정한다.
 * 5. 단일 출력: 단 하나의 System.out.printf() 메서드를 사용하여, "사번: [포맷1] | 이름: [포맷2] | 실적: [포맷3]\n" 형태로 콘솔에 한 줄로 출력한다. (각 포맷 자리에는 변수가 매칭되어야 함)
 */

public class SalaryFormatExample {

	public static void main(String[] args) {
		//%[값의 순번$][생략하면 왼쪽공백, -면 오른쪽공백,0이면 공백대신 0으로 채움][출력할 전체자릿수][.소수자릿수]변환문자(d f s)
		
		int empNo = 75;
		String empName = "이순신";
		double score = 85.6789;
		
		System.out.printf("사번: %1$05d | 이름: %2$-8s | 실적: %3$7.2f\n",empNo,empName,score);

	}

}
