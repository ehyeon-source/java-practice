package ch02.sec12;

/*
 * [문제 상황: 게임 캐릭터 전적 검색 결과 출력]
 * 
 * 1. 데이터 준비: 캐릭터의 레벨(level)은 7, 직업(jobClass)은 "마법사", 승률(winRate)은 65.8753이다. 각각 알맞은 타입의 변수에 할당한다. (변수명은 반드시 소문자로 시작할 것)
 * 2. 포맷팅 1 (0 채우기): 레벨은 총 3자리로 출력하되, 빈자리는 0으로 채워서 출력되도록 포맷을 지정한다.
 * 3. 포맷팅 2 (왼쪽 정렬): 직업은 총 10자리의 공간을 확보하고, 왼쪽으로 정렬하여 출력되도록 포맷을 지정한다.
 * 4. 포맷팅 3 (소수점 제어): 승률은 총 7자리의 공간을 차지하며, 소수점 아래 둘째 자리까지만 나타나도록 반올림하여 포맷을 지정한다.
 * 5. 단일 출력: 단 하나의 System.out.printf() 메서드를 사용하여, "LV: [포맷1] | 직업: [포맷2] | 승률: [포맷3]%%\n" 형태로 콘솔에 한 줄로 출력한다. 
 *    (주의: printf 안에서 퍼센트 기호 '%' 자체를 글자로 출력하려면 '%%'라고 두 번 적어야 합니다!)
 */

public class GameCharacterFormat {

	public static void main(String[] args) {
		int level = 7;
		String jobClass = "마법사";
		double winRate = 65.8753;
		
		System.out.printf("LV: %1$03d | 직업: %2$-10s | 승률: %3$7.2f%%\n",level,jobClass,winRate);
	}

}
