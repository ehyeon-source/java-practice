package ch03.sec10;

/*
 * [문제 상황: RPG 게임 캐릭터의 골드(Gold) 변동 추적 시스템]
 * 
 * 1. 초기 데이터: 플레이어의 현재 소지 골드를 나타내는 int 변수(gold)를 선언하고 0으로 초기화한다.
 * 2. 이벤트 연속 발생 (반드시 복합 대입 연산자만 사용할 것):
 *    - 이벤트 1: 던전 보상으로 1000 골드를 획득하여 누적한다. 콘솔에 현재 골드를 출력한다.
 *    - 이벤트 2: 함정을 밟아 250 골드를 잃었다. 콘솔에 현재 골드를 출력한다.
 *    - 이벤트 3: 도박장에 가서 현재 소지한 골드를 정확히 3배로 불렸다. 콘솔에 현재 골드를 출력한다.
 *    - 이벤트 4: 4인 파티 사냥이 끝난 후, 현재 소지한 골드를 4명이 똑같이 나누어 가졌다 (본인 몫만 변수에 다시 저장). 콘솔에 현재 골드를 출력한다.
 *    - 이벤트 5: 마을 은행에 가서 100 골드 단위 코인으로 모두 환전하고, 남은 100 골드 미만의 '자투리(나머지) 골드'만 주머니에 남겼다. 콘솔에 최종 자투리 골드를 출력한다.
 * 3. 주의사항: 모든 이벤트 과정에서 gold 변수는 단 하나만 사용되어야 하며, gold = gold + 1000 과 같은 중복 작성 방식은 엄격히 금지한다.
 */

public class AssignmentPractice {

	public static void main(String[] args) {
		int gold = 0;
		
		gold+=1000;
		System.out.println("현재골드: "+gold);
		
		gold-=250;
		System.out.println("현재골드: "+gold);
		
		gold*=3;
		System.out.println("현재골드: "+gold);
		
		gold/=4;
		System.out.println("현재골드: "+gold);
		
		gold%=100;
		System.out.println("현재골드: "+gold);
	}

}
