package ch07.sec07.company;
/*
 * [가동 조건]
 * - 관리자(자식) 객체를 하나 생성하되, 담는 그릇(변수 타입)은 반드시 '부모(일반 직원) 타입'으로 선언하여 담는다. (보내주신 코드의 A a1 = b; 와 같은 원리)
 * 
 * [테스트 순서 및 요구사항]
 * 1. 부모 그릇에 담긴 이 객체에게 업무(work)를 지시해 본다. (부모의 기본 업무가 나오는지, 개조된 관리자 업무가 나오는지 확인)
 * 2. 부모 그릇에 담긴 이 객체에게 관리자의 고유 기능인 휴가 승인(approveVacation)을 지시해 본다.
 * 3. 2번에서 컴파일 에러(빨간줄)가 발생하면 해당 줄을 주석(//) 처리하고, "본체는 관리자인데 왜 고유 기능을 쓸 수 없는지" 그 이유를 적어둔다.
 * 4. (가장 중요) 부모 그릇에 갇혀서 고유 기능을 못 쓰는 이 객체를, 다시 '관리자 타입'의 그릇으로 강제로 옮겨 담아(다운캐스팅) 본다.
 * 5. 강제로 옮겨 담은 새로운 변수를 통해 휴가 승인(approveVacation)을 다시 지시해 보고 정상 작동하는지 확인한다.
 */
public class HRApp {
	public static void main(String[] args) {
		Employee e = new Manager();
		
		e.work(); //내 예상 오버라이딩 된 메소드가 작동
		
		//e.approveVacation();  //참조변수가 부모타입으로 사실상 자식객체에 결합된 부모의 기능만 접근가능
		
		Manager m = (Manager)e;
		
		m.approveVacation();
	
	}

}
